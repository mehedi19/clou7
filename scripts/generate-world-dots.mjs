const inside = (x, y, poly) => {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};

// viewBox 1000 x 480, lon -170..190, lat 84..-58
const W = 1000, H = 480, LON0 = -170, LON1 = 190, LAT0 = 84, LAT1 = -58;
const step = 3.2;
const dots = [];
for (let lat = LAT0; lat >= LAT1; lat -= step) {
  for (let lon = LON0; lon <= LON1; lon += step) {
    if (Object.values(polys).some((p) => inside(lon, lat, p))) {
      dots.push([
        Math.round(((lon - LON0) / (LON1 - LON0)) * W),
        Math.round(((LAT0 - lat) / (LAT0 - LAT1)) * H),
      ]);
    }
  }
}
const out = `// AUTO-GENERATED by scripts/generate-world-dots.mjs — do not edit by hand.
// Stylised dotted world map, coordinates in a 1000 x 480 viewBox.
export const WORLD_DOTS: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(dots)};
`;
writeFileSync(new URL("../src/data/worldDots.ts", import.meta.url), out);
